/**
 * Claude Code「我说的」清洗 —— 后端权威版(option C:清洗归后端,抽屉/ingest 共用一份)。
 *
 * 逐字移植自原前端 `web/src/lib/cleanUserMessage.ts`(现已改为调本模块的后端端点)。
 * parity 测试(test/agentUserMessages.cleaners.test.ts)锁死与移植前语义一致。
 *
 * best-effort:只剥已知包装标记;剥完为空 → "",调用方据此丢弃该轮、不计数、is_human=0。
 */
import type { Message } from "../cursorHistory/types.js";

/**
 * 清洗版本。改动清洗规则必须 bump,触发 agent_user_messages 里 source='claude' 行的
 * cleaner_version 回填(从 raw_payload_json 重算)。有 pin 测试逼出有意识的版本升。
 */
export const CLAUDE_CLEANER_VERSION = 1;
export const CLAUDE_PARSER_VERSION = 1;

// 成对、可跨行的注入标记。
const PAIRED_TAGS = [
  "command-name",
  "command-message",
  "command-args",
  "command-contents",
  "local-command-stdout",
  "local-command-stderr",
  "system-reminder",
];

export function cleanClaudeUserMessage(raw: string): string {
  if (!raw) return "";

  // 0) 斜杠命令 / 技能调用:整轮机器展开,用户其实只敲了 `/xxx` 或触发技能 → 整轮丢弃。
  if (/<command-name>/.test(raw)) return "";
  if (raw.trimStart().startsWith("Base directory for this skill:")) return "";

  let s = raw;

  // 1) 成对标记整块(含内容,可跨行)。
  for (const tag of PAIRED_TAGS) {
    s = s.replace(new RegExp(`<${tag}>[\\s\\S]*?</${tag}>`, "g"), "");
  }

  // 2) 残留的未闭合 / 自闭合同类标记。
  s = s.replace(
    /<\/?(?:command-[a-z-]+|local-command-[a-z]+|system-reminder)[^>]*>/g,
    ""
  );

  // 3) Caveat 声明整行(Claude Code 在本地命令上下文前注入)。
  s = s.replace(
    /Caveat: The messages below were generated by the user while running local commands\.[^\n]*/g,
    ""
  );

  // 4) 中断提示行。
  s = s.replace(/\[Request interrupted by user[^\]]*\]/g, "");

  return s.trim();
}

export type ClaudeUserMessageExtract = {
  /** source_message_key:jsonl record.uuid(无则 user-L<line>,已是 Message.id)。 */
  messageKey: string;
  /** 消息时间戳(ms)。 */
  eventAtMs: number;
  /** 原始 body(userVisibleFromContent 拼接,未去注入)。 */
  rawText: string;
  /**
   * 重清洗输入。claude 清洗是**字符串→字符串**,故原始 body 即完整重清洗输入
   * (不像 opencode 需要 part 结构)。存为 JSON 字符串以统一 schema。
   */
  rawPayloadJson: string;
  cleanedText: string;
  isHuman: boolean;
};

/**
 * 从一个 session 的 Message[](buildClaudeSession 产出)抽「用户消息」。抽屉 + ingest 共用。
 * role 门在此(只取 role==='user')。纯注入轮也返回(cleaned='' / isHuman=false),
 * 由调用方决定留底(ingest)或省略(抽屉)。
 */
export function extractClaudeUserMessages(
  messages: Message[]
): ClaudeUserMessageExtract[] {
  const out: ClaudeUserMessageExtract[] = [];
  for (const m of messages) {
    if (m.role !== "user") continue;
    const rawText = m.content ?? "";
    const cleanedText = cleanClaudeUserMessage(rawText);
    out.push({
      messageKey: m.id ?? "",
      eventAtMs: new Date(m.timestamp).getTime(),
      rawText,
      rawPayloadJson: JSON.stringify(rawText),
      cleanedText,
      isHuman: cleanedText.trim().length > 0,
    });
  }
  return out;
}

/** 从 raw_payload_json 重算(cleaner_version 回填)。payload = JSON 编码的原始 body。 */
export function recleanClaudeFromPayload(rawPayloadJson: string): {
  cleanedText: string;
  isHuman: boolean;
} {
  let raw = "";
  try {
    const v = JSON.parse(rawPayloadJson) as unknown;
    if (typeof v === "string") raw = v;
  } catch {
    // 坏 payload → 空清洗
  }
  const cleanedText = cleanClaudeUserMessage(raw);
  return { cleanedText, isHuman: cleanedText.trim().length > 0 };
}
