/**
 * Claude Code「我说的」清洗 —— 后端权威版(option C:清洗归后端,抽屉/ingest 共用一份)。
 *
 * 逐字移植自原前端 `web/src/lib/cleanUserMessage.ts`(现已改为调本模块的后端端点)。
 * parity 测试(test/cleanUserMessage.test.ts)锁死与移植前语义一致。
 *
 * best-effort:只剥已知包装标记;剥完为空 → "",调用方据此丢弃该轮、不计数、is_human=0。
 */
import type { Message } from "../cursorHistory/types.js";

/**
 * 清洗版本。改动清洗规则必须 bump,触发 agent_user_messages 里 source='claude' 行的
 * cleaner_version 回填(从 raw_payload_json 重算)。有 pin 测试逼出有意识的版本升。
 */
// v2(2026-07-04):压缩摘要续接 / context 报告 / task-notification / 图片占位 过滤。
// v3(2026-07-04):命令/skill 调用不再丢弃 → 显示紧凑 /名字(用户裁定:调用 skill 是我的输入)。
// v4(2026-08-17):bash-* 三个标签。**注意这不是一刀切** —— 实测语料里 bash-input 与
//   bash-stdout/stderr 是 Claude Code 写出的**两条独立 user 消息**(各 63 条,全部
//   is_human=1):前者包的是你敲的命令,后者是执行结果。所以 bash-input 只剥标签留内容
//   (与 v3「调用 skill 是我的输入」同一裁定),stdout/stderr 整块剥(与 local-command-*
//   同类)。一刀切整块剥会让 63 条你敲过的命令从「我说的话」里消失。
export const CLAUDE_CLEANER_VERSION = 4;
export const CLAUDE_PARSER_VERSION = 1;

// 成对、可跨行的注入标记(整块剥,含内容)。
const PAIRED_TAGS = [
  "command-name",
  "command-message",
  "command-args",
  "command-contents",
  "local-command-stdout",
  "local-command-stderr",
  "system-reminder",
  "task-notification", // 后台任务完成通知注入(非人)。
  "bash-stdout", // ! 命令的执行结果(机器输出)。
  "bash-stderr",
];

/** 粘图占位/元数据:`[Image: …]` / `[Image #N]` / `[Image showing …]`(Claude Code 注入,非 prose)。 */
const CLAUDE_IMAGE_PLACEHOLDER_RE = /\[Images?\b[^\]]*\]/g;

export function cleanClaudeUserMessage(raw: string): string {
  if (!raw) return "";

  // 斜杠命令/skill 调用是你的输入 → 显示紧凑 /名字(+ 参数);展开的 skill 正文不算(用户裁定)。
  const cmd = /<command-name>\s*([^<]+?)\s*<\/command-name>/.exec(raw);
  if (cmd) {
    const name = cmd[1].trim(); // command-name 已含前导 /
    const argsM = /<command-args>\s*([\s\S]*?)\s*<\/command-args>/.exec(raw);
    const args = argsM ? argsM[1].trim() : "";
    return args ? `${name} ${args}` : name;
  }
  // 机器生成内容 → 直接丢弃:skill 正文注入、压缩摘要续接、/context 报告。
  const head = raw.trimStart();
  if (head.startsWith("Base directory for this skill:")) return "";
  // 上下文压缩后自动生成的摘要 + 续接指令(非人)。
  if (head.startsWith("This session is being continued from a previous conversation"))
    return "";
  // /context 命令报告(非人)。
  if (head.startsWith("## Context Usage") && head.includes("**Model:**")) return "";

  let s = raw;

  // 1) 成对标记整块(含内容,可跨行)。
  for (const tag of PAIRED_TAGS) {
    s = s.replace(new RegExp(`<${tag}>[\\s\\S]*?</${tag}>`, "g"), "");
  }

  // 2) 残留的未闭合 / 自闭合同类标记。
  //    `bash-[a-z]+` 在这里而**不在** PAIRED_TAGS 里,是为了让 <bash-input>ls</bash-input>
  //    只掉标签、留下 `ls` —— 那是你敲的命令。stdout/stderr 已在上一步整块剥掉,
  //    走到这里时只剩 bash-input 的一对标签。
  s = s.replace(
    /<\/?(?:command-[a-z-]+|local-command-[a-z]+|system-reminder|task-[a-z-]+|bash-[a-z]+)[^>]*>/g,
    ""
  );

  // 2.5) 图片占位/元数据:纯占位 → 剥完为空 → is_human=0;混在真人文字里 → 保留文字。
  s = s.replace(CLAUDE_IMAGE_PLACEHOLDER_RE, "");

  // 3) Caveat 声明整行(Claude Code 在本地命令上下文前注入)。
  s = s.replace(
    /Caveat: The messages below were generated by the user while running local commands\.[^\n]*/g,
    ""
  );

  // 4) 中断提示行。
  s = s.replace(/\[Request interrupted by user[^\]]*\]/g, "");

  return s.trim();
}

export type ClaudeUserMessageExtract = {
  /** source_message_key:jsonl record.uuid(无则 user-L<line>,已是 Message.id)。 */
  messageKey: string;
  /** 消息时间戳(ms)。 */
  eventAtMs: number;
  /** 原始 body(userVisibleFromContent 拼接,未去注入)。 */
  rawText: string;
  /**
   * 重清洗输入。claude 清洗是**字符串→字符串**,故原始 body 即完整重清洗输入
   * (不像 opencode 需要 part 结构)。存为 JSON 字符串以统一 schema。
   */
  rawPayloadJson: string;
  cleanedText: string;
  isHuman: boolean;
  /** V53:'user' | 'assistant'。 */
  role: "user" | "assistant";
  /** assistant 行在回答的那条 user 消息的 messageKey;user 行恒为 null。 */
  answeringUserKey: string | null;
};

/**
 * 从一个 session 的 Message[](buildClaudeSession 产出)抽消息。抽屉 + ingest 共用。
 *
 * **两侧判据不同,这是有意的**:
 *
 * - **user**:沿用 V53 之前的口径 —— 收**全部** user 消息,不看 readingHidden。
 *   纯注入轮也返回(cleaned='' / isHuman=false),由调用方决定留底(ingest)或省略(抽屉)。
 *   改这条会让既有的 4.9 万条 is_human=0 留底行凭空消失,直接违反回归基线。
 * - **assistant**:用 `readingHidden` 判据,只收「阅读模式下可见」的行。assistant 侧
 *   没有历史包袱,而 readingHidden 已在真实语料上验证一周(滤掉 98.6% 的字节)。
 *
 * 纯 thinking 行(text 空、thinking 非空)**跳过**:它 readingHidden 为空(是 AI 的真实
 * 输出,不该在阅读模式里藏掉),但 cleaned_text 会是空串,而 store 层对每行无条件
 * syncFtsRow —— 空串会进 FTS 索引。实测全量语料只有 20 条,不值得为它引入一个
 * 「有内容但不索引」的第三态。
 *
 * `answeringUserKey` 靠顺序扫描:表里只有 kept 行,同会话内 assistant 前面最近的那条
 * user 就是它在回答的提问。实测 13294 条 kept assistant 100% 能找到前置 user。
 */
export function extractClaudeMessages(
  messages: Message[]
): ClaudeUserMessageExtract[] {
  const out: ClaudeUserMessageExtract[] = [];
  let lastUserKey: string | null = null;

  for (const m of messages) {
    if (m.role === "user") {
      const rawText = m.content ?? "";
      const cleanedText = cleanClaudeUserMessage(rawText);
      const messageKey = m.id ?? "";
      // 锚点只认「人说的话」——纯注入轮(cleaned 为空)不该成为 AI 回答的提问上下文。
      if (cleanedText.trim().length > 0) lastUserKey = messageKey;
      out.push({
        messageKey,
        eventAtMs: new Date(m.timestamp).getTime(),
        rawText,
        rawPayloadJson: JSON.stringify(rawText),
        cleanedText,
        isHuman: cleanedText.trim().length > 0,
        role: "user",
        answeringUserKey: null,
      });
      continue;
    }

    if (m.role !== "assistant") continue;
    // 阅读模式藏掉的(tool-only / appendix)不入库。
    if ((m.metadata as { readingHidden?: string } | undefined)?.readingHidden) {
      continue;
    }
    const body = m.content ?? "";
    // 纯 thinking 行:见上方注释,跳过而不是写空串。
    if (!body.trim()) continue;
    out.push({
      messageKey: m.id ?? "",
      eventAtMs: new Date(m.timestamp).getTime(),
      rawText: body,
      rawPayloadJson: JSON.stringify(body),
      // AI 输出不经清洗 —— 它不会往自己嘴里塞 system-reminder。
      cleanedText: body,
      isHuman: false,
      role: "assistant",
      answeringUserKey: lastUserKey,
    });
  }
  return out;
}

/**
 * 只要 user 消息(「只看我说的」抽屉用,语义与 V53 之前完全一致)。
 * 名字保持诚实:它确实只返回 user 行。ingest 要连 AI 一起收,用 `extractClaudeMessages`。
 */
export function extractClaudeUserMessages(
  messages: Message[]
): ClaudeUserMessageExtract[] {
  return extractClaudeMessages(messages).filter((m) => m.role === "user");
}

/** 从 raw_payload_json 重算(cleaner_version 回填)。payload = JSON 编码的原始 body。 */
export function recleanClaudeFromPayload(rawPayloadJson: string): {
  cleanedText: string;
  isHuman: boolean;
} {
  let raw = "";
  try {
    const v = JSON.parse(rawPayloadJson) as unknown;
    if (typeof v === "string") raw = v;
  } catch {
    // 坏 payload → 空清洗
  }
  const cleanedText = cleanClaudeUserMessage(raw);
  return { cleanedText, isHuman: cleanedText.trim().length > 0 };
}
